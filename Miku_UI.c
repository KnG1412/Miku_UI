static void addDirtyRect(int l, int t, int r, int b, int hud)
{
    if (g_rectCount >= (int)ARRAYSIZE(g_rects)) return;
    if (l < 0) l = 0;
    if (t < 0) t = 0;
    if (r > g_width) r = g_width;
    if (b > g_height) b = g_height;
    if (r <= l || b <= t) return;
    g_rects[g_rectCount].left = l;
    g_rects[g_rectCount].top = t;
    g_rects[g_rectCount].right = r;
    g_rects[g_rectCount].bottom = b;
    g_rectHud[g_rectCount] = hud;
    ++g_rectCount;
}

static void computeLayout(void)
{
    LAYOUT *L = &g_lay;
    float scale, drawW, drawH, left, top;

    L->sideW = (float)clampDouble((double)g_width * 0.19, 245.0, 330.0);
    L->margin = (float)clampDouble((double)g_width * 0.022, 20.0, 38.0);
    L->leftX = L->margin + g_uiShift;
    L->topY = (float)g_height * 0.085f;
    L->centerY = (float)g_height * 0.405f;
    L->graphY = (float)g_height -
        (float)clampDouble((double)g_height * 0.185, 130.0, 190.0);
    L->graphH = (float)g_height - L->graphY - L->margin;
    L->leftY2 = L->topY + 110.0f; /* CPU card is 98 px tall + 12 px gap */
    L->leftY3 = L->leftY2 + 136.0f;
    L->rightY2 = L->topY + 220.0f;
    L->activityH = 420.0f;

    if (g_width < 1450)
        L->sideW = (float)clampDouble((double)g_width * 0.205, 220.0, 285.0);
    L->rightX = (float)g_width - L->margin - L->sideW;
    L->centerX = (L->leftX + L->sideW + L->rightX) * 0.5f;
    L->freeW = L->rightX - (L->leftX + L->sideW) - 8.0f;
    if (L->freeW < 160.0f) L->freeW = 160.0f;
    L->mikuMaxH = (float)clampDouble((double)g_height * 0.72, 260.0, 760.0);

    /* Only these regions ever change. The centre of the screen (where the Miku
       art lives, or nothing when it is hidden) is never repainted per tick. */
    g_rectCount = 0;
    addDirtyRect((int)L->leftX - 14, 16, (int)L->leftX + 260, 72, 0);                     /* title      */
    addDirtyRect(g_width - (int)L->margin - 214, 16, g_width, 72, 0);                     /* autostart  */
    addDirtyRect((int)L->leftX - 4, g_height - 26, (int)L->leftX + 720, g_height, 0);     /* key hints  */
    addDirtyRect((int)L->leftX - 12, (int)L->topY - 6,
                 (int)(L->leftX + L->sideW) + 6, (int)(L->leftY3 + 158.0f + 146.0f) + 6, 1); /* left cards  */
    addDirtyRect((int)L->rightX - 6, (int)L->topY - 6,
                 (int)(L->rightX + L->sideW) + 6, (int)(L->rightY2 + L->activityH) + 6, 1);   /* right cards */
    addDirtyRect((int)L->leftX - 6, (int)L->graphY - 6,
                 g_width - (int)L->margin + 6, (int)(L->graphY + L->graphH) + 6, 1);          /* history     */

    /* Destination rectangle of the (static) ASCII art. */
    scale = L->mikuMaxH / (float)MIKU_ART_HEIGHT;
    if ((float)MIKU_ART_WIDTH * scale > L->freeW)
        scale = L->freeW / (float)MIKU_ART_WIDTH;
    if (scale <= 0.0f) {
        SetRectEmpty(&g_mikuRect);
        return;
    }
    drawW = (float)MIKU_ART_WIDTH * scale;
    drawH = (float)MIKU_ART_HEIGHT * scale;
    left = L->centerX - drawW * 0.5f;
    top = L->centerY - drawH * 0.5f;
    g_mikuRect.left = roundi(left);
    g_mikuRect.top = roundi(top);
    g_mikuRect.right = g_mikuRect.left + (roundi(drawW) > 1 ? roundi(drawW) : 1);
    g_mikuRect.bottom = g_mikuRect.top + (roundi(drawH) > 1 ? roundi(drawH) : 1);
}


/* Rasterize the embedded ASCII art ONCE into a temporary DIB, stretch it onto
   the window, then free the DIB. Nothing stays resident afterwards. It is only
   called again when the window gets invalidated (display change, etc.). */
static void drawMiku(HDC windowDC)
{
    HDC memoryDC;
    HBITMAP bitmap = NULL;
    HGDIOBJ oldBitmap = NULL;
    HGDIOBJ oldFont = NULL;
    HFONT font = NULL;
    BITMAPINFO bmi;
    void *bits = NULL;
    DWORD lastColor = 0xFFFFFFFFu;
    int row, col;
    const int dw = g_mikuRect.right - g_mikuRect.left;
    const int dh = g_mikuRect.bottom - g_mikuRect.top;

    if (dw <= 0 || dh <= 0) return;
    memoryDC = CreateCompatibleDC(windowDC);
    if (!memoryDC) return;

    ZeroMemory(&bmi, sizeof(bmi));
    bmi.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    bmi.bmiHeader.biWidth = MIKU_ART_WIDTH;
    bmi.bmiHeader.biHeight = -MIKU_ART_HEIGHT;
    bmi.bmiHeader.biPlanes = 1;
    bmi.bmiHeader.biBitCount = 32;
    bmi.bmiHeader.biCompression = BI_RGB;
    /* A new DIB section is zero-filled by the OS, i.e. already "transparent". */
    bitmap = CreateDIBSection(memoryDC, &bmi, DIB_RGB_COLORS, &bits, NULL, 0);
    if (!bitmap || !bits) goto cleanup;
    oldBitmap = SelectObject(memoryDC, bitmap);

    font = CreateFontW(-MIKU_CELL_H, MIKU_CELL_W, 0, 0, FW_NORMAL,
        FALSE, FALSE, FALSE, ANSI_CHARSET, OUT_TT_PRECIS, CLIP_DEFAULT_PRECIS,
        ANTIALIASED_QUALITY, FIXED_PITCH | FF_MODERN, L"Consolas");
    if (font) oldFont = SelectObject(memoryDC, font);
    SetBkMode(memoryDC, TRANSPARENT);
    SetTextAlign(memoryDC, TA_LEFT | TA_TOP | TA_NOUPDATECP);

    for (row = 0; row < MIKU_ASCII_ROWS; ++row) {
        for (col = 0; col < MIKU_ASCII_COLS; ++col) {
            char ch = g_asciiMikuRows[row][col];
            unsigned int index, hexOffset;
            DWORD color;
            WCHAR glyph;
            if (ch == ' ') continue;
            hexOffset = (unsigned int)col * 2u;
            index = (hexDigitValue(g_asciiMikuColorHex[row][hexOffset]) << 4) |
                    hexDigitValue(g_asciiMikuColorHex[row][hexOffset + 1u]);
            color = g_asciiMikuPalette[index];
            if (color != lastColor) {
                SetTextColor(memoryDC, RGB((color >> 16) & 0xFFu,
                                           (color >> 8) & 0xFFu,
                                           color & 0xFFu));
                lastColor = color;
            }
            glyph = (WCHAR)(unsigned char)ch;
            TextOutW(memoryDC, col * MIKU_CELL_W, row * MIKU_CELL_H, &glyph, 1);
        }
    }

    SetStretchBltMode(windowDC, HALFTONE);
    SetBrushOrgEx(windowDC, 0, 0, NULL);
    StretchBlt(windowDC, g_mikuRect.left, g_mikuRect.top, dw, dh,
               memoryDC, 0, 0, MIKU_ART_WIDTH, MIKU_ART_HEIGHT, SRCCOPY);

    GdiFlush();

cleanup:
    if (oldFont) SelectObject(memoryDC, oldFont);
    if (font) DeleteObject(font);
    if (oldBitmap && oldBitmap != HGDI_ERROR) SelectObject(memoryDC, oldBitmap);
    if (bitmap) DeleteObject(bitmap);
    DeleteDC(memoryDC);
}

