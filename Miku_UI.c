static void drawSeries(const double *series, int count, int head, float x, float y,
                       float w, float h, float r, float g, float b, float a)
{
    int i;
    int havePrev = 0;
    float prevX = 0.0f, prevY = 0.0f;
    for (i = 0; i < count; ++i) {
        int idx = (head - count + i + HISTORY_N) % HISTORY_N;
        double v = series[idx];
        float px, py;
        if (v < 0.0) {
            havePrev = 0; /* gap in the data: break the line */
            continue;
        }
        if (v > 100.0) v = 100.0;
        px = x + (count <= 1 ? 0.0f : ((float)i / (float)(count - 1)) * w);
        py = y + h - (float)(v / 100.0) * h;
        if (havePrev) aaSegment(prevX, prevY, px, py, 1.35f, r, g, b, a);
        prevX = px;
        prevY = py;
        havePrev = 1;
    }
}

