static void setGpuUnavailable(void)
{
    g_metrics.intelGpuPercent = -1.0;
    g_metrics.nvidiaGpuPercent = -1.0;
}

/* The buffer capacity is remembered between ticks, so normally a single
   PdhGetFormattedCounterArrayW call per second is enough. */
static void pollGpuUsage(void)
{
    static BYTE *buffer = NULL;
    static DWORD bufferCapacity = 0;
    static ENGINE_BUCKET buckets[MAX_BUCKETS];
    DWORD bufferSize = 0;
    DWORD itemCount = 0;
    PDH_STATUS status = PDH_MORE_DATA;
    int bucketCount = 0;
    int attempt;
    DWORD i;
    double perAdapter[MAX_ADAPTERS];

    if (!g_gpuCounterReady || !g_gpuQuery || !g_gpuEngineCounter) {
        setGpuUnavailable();
        return;
    }
    if (PdhCollectQueryData(g_gpuQuery) != ERROR_SUCCESS) {
        setGpuUnavailable();
        return;
    }

    for (attempt = 0; attempt < 3; ++attempt) {
        bufferSize = bufferCapacity;
        itemCount = 0;
        status = PdhGetFormattedCounterArrayW(g_gpuEngineCounter, PDH_FMT_DOUBLE,
            &bufferSize, &itemCount, (PPDH_FMT_COUNTERVALUE_ITEM_W)buffer);
        if (status != PDH_MORE_DATA) break;
        if (bufferSize == 0) break;
        {
            DWORD newCapacity = bufferSize + bufferSize / 4 + 256;
            BYTE *newBuffer = (BYTE *)realloc(buffer, newCapacity);
            if (!newBuffer) {
                setGpuUnavailable();
                return;
            }
            buffer = newBuffer;
            bufferCapacity = newCapacity;
        }
    }
    if (status != ERROR_SUCCESS || itemCount == 0 || !buffer) {
        setGpuUnavailable();
        return;
    }

    for (i = 0; i < itemCount; ++i) {
        PPDH_FMT_COUNTERVALUE_ITEM_W it = &((PPDH_FMT_COUNTERVALUE_ITEM_W)buffer)[i];
        int adapterIndex, physicalIndex = -1, engineIndex = -1;
        const WCHAR *p;
        double value;
        int j, found = -1;
        if (it->FmtValue.CStatus != ERROR_SUCCESS || !it->szName) continue;
        value = it->FmtValue.doubleValue;
        if (value < 0.0) continue;
        if (value > 100.0) value = 100.0;
        adapterIndex = adapterIndexFromLuidText(it->szName);
        if (adapterIndex < 0) continue;
        p = wcsstr(it->szName, L"phys_");
        if (!p || swscanf_s(p, L"phys_%d_eng_%d", &physicalIndex, &engineIndex) != 2) continue;

        for (j = 0; j < bucketCount; ++j) {
            if (buckets[j].adapterIndex == adapterIndex &&
                buckets[j].physicalIndex == physicalIndex &&
                buckets[j].engineIndex == engineIndex) {
                found = j;
                break;
            }
        }
        if (found >= 0) {
            buckets[found].utilization += value;
        } else if (bucketCount < MAX_BUCKETS) {
            buckets[bucketCount].adapterIndex = adapterIndex;
            buckets[bucketCount].physicalIndex = physicalIndex;
            buckets[bucketCount].engineIndex = engineIndex;
            buckets[bucketCount].utilization = value;
            ++bucketCount;
        }
    }

    for (i = 0; i < MAX_ADAPTERS; ++i) perAdapter[i] = -1.0;
    for (i = 0; i < (DWORD)bucketCount; ++i) {
        int a = buckets[i].adapterIndex;
        double v = buckets[i].utilization;
        if (v > 100.0) v = 100.0;
        if (v < 0.0) v = 0.0;
        if (a >= 0 && a < MAX_ADAPTERS && (perAdapter[a] < 0.0 || v > perAdapter[a]))
            perAdapter[a] = v;
    }
    g_metrics.intelGpuPercent = (g_intelAdapter >= 0 && g_intelAdapter < MAX_ADAPTERS)
        ? perAdapter[g_intelAdapter] : -1.0;
    g_metrics.nvidiaGpuPercent = (g_nvidiaAdapter >= 0 && g_nvidiaAdapter < MAX_ADAPTERS)
        ? perAdapter[g_nvidiaAdapter] : -1.0;
}

