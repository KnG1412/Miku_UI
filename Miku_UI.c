static WCHAR g_cpuName[96];

/* Removes "(R)" / "(TM)", collapses spaces, and drops the noisy tails:
   " @ 2.30GHz", " with Radeon Graphics", trailing " CPU". */
static void cleanHardwareName(const WCHAR *src, WCHAR *out, size_t outCount)
{
    size_t o = 0, n;
    WCHAR *p;
    if (!out || outCount == 0) return;
    out[0] = L'\0';
    if (!src) return;
    while (*src && o + 1 < outCount) {
        if (src[0] == L'(' && (src[1] == L'R' || src[1] == L'r') && src[2] == L')') { src += 3; continue; }
        if (src[0] == L'(' && (src[1] == L'T' || src[1] == L't') &&
            (src[2] == L'M' || src[2] == L'm') && src[3] == L')') { src += 4; continue; }
        if (src[0] == L' ' && (o == 0 || out[o - 1] == L' ')) { ++src; continue; }
        out[o++] = *src++;
    }
    out[o] = L'\0';
    p = wcsstr(out, L" @");
    if (p) *p = L'\0';
    p = wcsstr(out, L" with ");
    if (p) *p = L'\0';
    n = wcslen(out);
    while (n > 0 && out[n - 1] == L' ') out[--n] = L'\0';
    if (n >= 4 && wcscmp(out + n - 4, L" CPU") == 0) out[n - 4] = L'\0';
}

/* Splits a long name into two lines at the last space that fits line 1. */
static void splitHardwareName(const WCHAR *name, int max1, int max2,
                              WCHAR *l1, size_t n1, WCHAR *l2, size_t n2)
{
    int len = (int)wcslen(name);
    int cut = max1;
    l1[0] = L'\0';
    l2[0] = L'\0';
    if (len <= max1) {
        _snwprintf_s(l1, n1, _TRUNCATE, L"%ls", name);
        return;
    }
    while (cut > 0 && name[cut] != L' ') --cut;
    if (cut <= 0) cut = max1;
    _snwprintf_s(l1, n1, _TRUNCATE, L"%.*ls", cut, name);
    while (name[cut] == L' ') ++cut;
    _snwprintf_s(l2, n2, _TRUNCATE, L"%.*ls", max2, name + cut);
}

static void readCpuName(void)
{
    HKEY key = NULL;
    WCHAR raw[128];
    DWORD bytes = (DWORD)(sizeof(raw) - sizeof(WCHAR));
    DWORD type = 0;
    raw[0] = L'\0';
    if (RegOpenKeyExW(HKEY_LOCAL_MACHINE,
            L"HARDWARE\\DESCRIPTION\\System\\CentralProcessor\\0",
            0, KEY_QUERY_VALUE, &key) == ERROR_SUCCESS) {
        if (RegQueryValueExW(key, L"ProcessorNameString", NULL, &type,
                (BYTE *)raw, &bytes) == ERROR_SUCCESS && type == REG_SZ)
            raw[bytes / sizeof(WCHAR)] = L'\0';
        else
            raw[0] = L'\0';
        RegCloseKey(key);
    }
    cleanHardwareName(raw, g_cpuName, ARRAYSIZE(g_cpuName));
}

